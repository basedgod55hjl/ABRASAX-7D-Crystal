def list_kernels() -> list[dict[str, Any]]:
	"""Return info for all registered kernels."""
	result = []
	for alias, kinfo in KERNEL_REGISTRY.items():
		result.append({
			"name": alias,
			"function": kinfo.func_name,
			"module": kinfo.module,
			"dim": kinfo.dim,
		})
	return result


def print_kernel_table() -> None:
	"""Print a formatted table of all registered kernels."""
	rows = list_kernels()
	print(f"\n{'Python Name':35s} {'CUDA Function':40s} {'Module':8s} {'Dim':4s}")
	print("-" * 90)
	for r in sorted(rows, key=lambda x: (x["module"], x["name"])):
		print(f"{r['name']:35s} {r['function']:40s} {r['module']:8s} {r['dim']:4d}")
	print(f"\nTotal: {len(rows)} kernels")
