class DeviceArray:
	"""Handle to GPU device memory allocated via CUDA Driver API.

	Attributes:
		cuptr: CUdeviceptr value (device address as int).
		size_bytes: Size of allocation in bytes.
	"""

	__slots__ = ("cuptr", "size_bytes", "_finalizer")

	def __init__(self, cuptr: int, size_bytes: int,
				 finalizer: Callable[[], None] | None = None) -> None:
		self.cuptr = cuptr
		self.size_bytes = size_bytes
		self._finalizer = finalizer

	def __repr__(self) -> str:
		return (f"<DeviceArray ptr=0x{self.cuptr:016x} "
				f"size={self.size_bytes} bytes ({self.size_bytes // 4} floats)>")

	@property
	def nbytes(self) -> int:
		return self.size_bytes

	@property
	def nfloats(self) -> int:
		"""Number of float32 elements this allocation holds."""
		return self.size_bytes // 4

	def free(self) -> None:
		"""Explicitly free device memory."""
		if self._finalizer is not None:
			self._finalizer()
			self._finalizer = None


