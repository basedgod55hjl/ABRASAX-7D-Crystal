	def mhq7d_attention(
		self,
		Q: np.ndarray,
		K: np.ndarray,
		V: np.ndarray,
		heads: int,
		dim: int,
	) -> np.ndarray:
		"""7D Manifold-Constrained Attention.

		Kernel: mhq7d_attention (v1)
		"""
		assert Q.dtype == np.float32 and K.dtype == np.float32 and V.dtype == np.float32
		n = Q.size
		d_q = self.alloc(n * 4)
		d_k = self.alloc(n * 4)
		d_v = self.alloc(n * 4)
		d_o = self.alloc(n * 4)
		try:
			self.to_device(d_q, Q)
			self.to_device(d_k, K)
			self.to_device(d_v, V)
			# h = blockIdx.x, i = threadIdx.x in the kernel, so the launch
			# must be one BLOCK per head and one THREAD per dim. With no grid
			# the loader defaults to (1,1,1) and only head 0 is ever computed
			# (measured 2026-11-01: heads=1 exact, heads=2 err 0.60,
			# heads=4 err 1.17).
			self.launch_kernel(
				"mhq7d_attention",
				(d_q, d_k, d_v, d_o, np.int32(heads), np.int32(dim)),
				grid=(heads, 1, 1),
				block=(dim, 1, 1),
			)
			return self.from_device(d_o, Q.shape)
		finally:
			self.free(d_q)
			self.free(d_k)
			self.free(d_v)
			self.free(d_o)

	def mhq7d_persistent(
		self,
		manifold_size: int,
		stream: ctypes.c_void_p | None = None,
	) -> tuple[DeviceArray, ctypes.c_void_p | None]:
		"""Start a persistent GPU keep-alive kernel.

		The kernel loops until manifold[0] == 999.0f. Returns (manifold, stream).
		Call stop_persistent() to terminate.

		Kernel: mhq7d_persistent (v1)
		"""
		d_manifold = self.alloc(manifold_size * 4)
		if stream is None:
			stream = self.create_stream()
		self.launch_kernel(
			"mhq7d_persistent",
			(d_manifold, np.int32(manifold_size)),
			stream=stream,
			first_array_n=manifold_size,
		)
		return d_manifold, stream

	def stop_persistent(
		self,
		manifold: DeviceArray,
		stream: ctypes.c_void_p | None = None,
		timeout_ms: float = 1000.0,
	) -> None:
		"""Signal a persistent kernel to terminate and wait for completion."""
		# Set manifold[0] = 999.0f to signal termination
		signal_arr = np.array([999.0], dtype=np.float32)
		self.to_device(manifold, signal_arr)
		time.sleep(timeout_ms / 1000.0)
		if stream is not None:
			try:
				self.sync_stream(stream)
			except Exception:
				pass
		self.sync()

	def manifold_projection_v1(
		self,
		input_arr: np.ndarray,
		dim: int,
	) -> np.ndarray:
		"""Project input onto 7D Poincare ball (v1 kernel).

		Kernel: manifold_projection_kernel (v1)
		"""
		assert input_arr.dtype == np.float32
		n = input_arr.size
		d_in = self.alloc(n * 4)
		d_out = self.alloc(n * 4)
		try:
			self.to_device(d_in, input_arr)
			self.launch_kernel(
				"manifold_projection",
				(d_in, d_out, np.int32(n), np.int32(dim)),
				first_array_n=n,
			)
			return self.from_device(d_out, input_arr.shape)
		finally:
			self.free(d_in)
			self.free(d_out)

	def phi_modulation(
		self,
		data: np.ndarray,
		phase: float = 0.0,
	) -> np.ndarray:
		"""Apply golden ratio modulation to data (v1).

		Kernel: phi_modulation_kernel (v1)
		"""
		return self._launch_1d_inplace(
			"phi_modulation",
			data,
			(np.int32(data.size), np.float32(phase)),
		)

	def cbm_flux_unfold_v1(
		self,
		seed: np.ndarray,
		matrix_size: int,
		phi_flux: float = 0.1,
	) -> np.ndarray:
		"""DNA Crystal Activation unfold (v1 kernel).

		Kernel: cbm_flux_unfold_kernel (v1)
		"""
		assert seed.dtype == np.float32
		d_seed = self.alloc(seed.nbytes)
		d_out = self.alloc(matrix_size * 4)
		try:
			self.to_device(d_seed, seed)
			self.launch_kernel(
				"cbm_flux_unfold",
				(d_seed, d_out, np.int32(seed.size), np.int32(matrix_size),
				 np.float32(phi_flux)),
				first_array_n=matrix_size,
			)
			return self.from_device(d_out, (matrix_size,))
		finally:
			self.free(d_seed)
			self.free(d_out)

	# -- physx kernel -------------------------------------------------------

	def physx_crystal_dynamics(
		self,
		positions: np.ndarray,	 # (n_bodies, 7) float32
		velocities: np.ndarray,	 # (n_bodies, 7) float32
		masses: np.ndarray,		 # (n_bodies,) float32
		resonances: np.ndarray,	 # (n_bodies,) float32
		cosmos_predictions: np.ndarray | None = None,  # (n_bodies, 7) or None
		dt: float = 0.01,
	) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
		"""Run PhysX crystal dynamics simulation step.

		Kernel: physx_crystal_dynamics_kernel (physx)
		Accepts CrystalRigidBody AOS layout and returns updated bodies.

		Args:
			positions: (N, 7) array of body positions.
			velocities: (N, 7) array of body velocities.
			masses: (N,) array of body masses.
			resonances: (N,) array of body resonance values.
			cosmos_predictions: Optional (N, 7) external force predictions.
			dt: Time step.

		Returns:
			(positions, velocities, masses, resonances) after one physics step.
		"""
		n_bodies = len(masses)
		assert positions.shape == (n_bodies, 7), "positions must be (N, 7)"
		assert velocities.shape == (n_bodies, 7), "velocities must be (N, 7)"
		assert masses.shape == (n_bodies,), "masses must be (N,)"
		assert resonances.shape == (n_bodies,), "resonances must be (N,)"

		# Pack into CrystalRigidBody array: [pos(7), vel(7), mass, resonance] * N
		# Each body is 16 x float32 = 64 bytes
		body_size = 16  # floats per body
		bodies_host = np.zeros(n_bodies * body_size, dtype=np.float32)
		for i in range(n_bodies):
			base = i * body_size
			bodies_host[base:base + 7] = positions[i]
			bodies_host[base + 7:base + 14] = velocities[i]
			bodies_host[base + 14] = masses[i]
			bodies_host[base + 15] = resonances[i]

		d_bodies = self.alloc(n_bodies * body_size * 4)
		d_cosmos: DeviceArray | None = None
		try:
			self.to_device(d_bodies, bodies_host)

			# Handle optional cosmos predictions
			cosmos_ptr: DeviceArray | None = None
			if cosmos_predictions is not None:
				assert cosmos_predictions.shape == (n_bodies, 7), \
					f"cosmos_predictions must be (N, 7), got {cosmos_predictions.shape}"
				d_cosmos = self.alloc(n_bodies * 7 * 4)
				self.to_device(d_cosmos, cosmos_predictions.flatten())
				cosmos_ptr = d_cosmos
			else:
				# Pass NULL (will be nullptr in the kernel)
				cosmos_ptr = DeviceArray(0, 0)  # cuptr=0 -> nullptr

			self.launch_kernel(
				"physx_crystal_dynamics",
				(d_bodies, cosmos_ptr, np.int32(n_bodies), np.float32(dt)),
				first_array_n=n_bodies,
			)

			# Read back and unpack
			bodies_out = self.from_device(
				d_bodies, (n_bodies * body_size,)
			)
			new_positions = np.zeros((n_bodies, 7), dtype=np.float32)
			new_velocities = np.zeros((n_bodies, 7), dtype=np.float32)
			new_masses = np.zeros(n_bodies, dtype=np.float32)
			new_resonances = np.zeros(n_bodies, dtype=np.float32)
			for i in range(n_bodies):
				base = i * body_size
				new_positions[i] = bodies_out[base:base + 7]
				new_velocities[i] = bodies_out[base + 7:base + 14]
				new_masses[i] = bodies_out[base + 14]
				new_resonances[i] = bodies_out[base + 15]

			return new_positions, new_velocities, new_masses, new_resonances
		finally:
			self.free(d_bodies)
			if d_cosmos is not None:
				self.free(d_cosmos)

	# ------------------------------------------------------------------
	#  Shutdown
	# ------------------------------------------------------------------

	def close(self) -> None:
		"""Release all CUDA resources."""
		for name, mod in list(self._modules.items()):
			try:
				self._driver.cuModuleUnload(mod)
				logger.debug("Unloaded module: %s", name)
			except Exception as exc:
				logger.warning("Failed to unload module %s: %s", name, exc)
		self._modules.clear()
		self._functions.clear()

		if self._context is not None:
			try:
				self._driver.cuCtxDestroy(self._context)
				logger.debug("Destroyed CUDA context")
			except Exception as exc:
				logger.warning("Failed to destroy context: %s", exc)
			self._context = None

	def __enter__(self) -> CrystalKernelRuntime:
		return self

	def __exit__(self, *args: Any) -> None:
		self.close()


