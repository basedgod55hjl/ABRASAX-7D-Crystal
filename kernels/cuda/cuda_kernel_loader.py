# ===================================================================
#  CUDA Driver API -- ctypes binding to nvcuda.dll
# ===================================================================

class CudaDriverAPI:
	"""Low-level ctypes binding to the CUDA Driver API (nvcuda.dll)."""

	def __init__(self) -> None:
		self._lib: ctypes.CDLL | None = None
		self._load_library()

	# --- function pointer attributes (set in _bind_functions) ---
	cuInit: Callable = None			# type: ignore[assignment]
	cuDeviceGetCount: Callable = None	# type: ignore[assignment]
	cuDeviceGet: Callable = None		# type: ignore[assignment]
	cuDeviceGetName: Callable = None	# type: ignore[assignment]
	cuDeviceGetAttribute: Callable = None  # type: ignore[assignment]
	cuDeviceTotalMem: Callable = None	# type: ignore[assignment]
	cuCtxCreate: Callable = None		# type: ignore[assignment]
	cuCtxSetCurrent: Callable = None	# type: ignore[assignment]
	cuCtxGetCurrent: Callable = None	# type: ignore[assignment]
	cuCtxSynchronize: Callable = None	# type: ignore[assignment]
	cuCtxDestroy: Callable = None		# type: ignore[assignment]
	cuModuleLoadData: Callable = None	# type: ignore[assignment]
	cuModuleGetFunction: Callable = None  # type: ignore[assignment]
	cuModuleUnload: Callable = None		# type: ignore[assignment]
	cuMemAlloc: Callable = None			# type: ignore[assignment]
	cuMemFree: Callable = None			# type: ignore[assignment]
	cuMemcpyHtoD: Callable = None		# type: ignore[assignment]
	cuMemcpyDtoH: Callable = None		# type: ignore[assignment]
	cuMemsetD8: Callable = None		# type: ignore[assignment]
	cuMemsetD32: Callable = None		# type: ignore[assignment]
	cuLaunchKernel: Callable = None		# type: ignore[assignment]
	cuStreamCreate: Callable = None		# type: ignore[assignment]
	cuStreamDestroy: Callable = None	# type: ignore[assignment]
	cuStreamSynchronize: Callable = None  # type: ignore[assignment]
	cuGetErrorString: Callable = None	# type: ignore[assignment]

	def _load_library(self) -> None:
		"""Load nvcuda.dll (CUDA Driver API, shipped with NVIDIA drivers)."""
		for libname in ("nvcuda.dll",):
			try:
				self._lib = ctypes.CDLL(libname)
				logger.debug("Loaded CUDA Driver API: %s", libname)
				break
			except OSError as exc:
				logger.debug("Failed to load %s: %s", libname, exc)
		else:
			raise RuntimeError(
				"Failed to load nvcuda.dll -- NVIDIA drivers required."
			)
		self._bind_functions()

	def _bind_functions(self) -> None:
		"""Bind all CUDA Driver API functions with argtypes/restype."""
		lib = self._lib
		# Use a helper to reduce boilerplate
		def bind(name: str, argtypes: list[Any], restype: type = ctypes.c_int) -> Any:
			fn = getattr(lib, name)
			fn.argtypes = argtypes
			fn.restype = restype
			return fn

		# Initialization
		self.cuInit = bind("cuInit", [ctypes.c_uint])
		self.cuDeviceGetCount = bind("cuDeviceGetCount",
			[ctypes.POINTER(ctypes.c_int)])
		self.cuDeviceGet = bind("cuDeviceGet",
			[ctypes.POINTER(ctypes.c_int), ctypes.c_int])
		self.cuDeviceGetName = bind("cuDeviceGetName",
			[ctypes.c_char_p, ctypes.c_int, ctypes.c_int])
		self.cuDeviceGetAttribute = bind("cuDeviceGetAttribute",
			[ctypes.POINTER(ctypes.c_int), ctypes.c_int, ctypes.c_int])
		self.cuDeviceTotalMem = bind("cuDeviceTotalMem",
			[ctypes.POINTER(ctypes.c_size_t), ctypes.c_int])

		# Context management
		self.cuCtxCreate = bind("cuCtxCreate",
			[ctypes.POINTER(ctypes.c_void_p), ctypes.c_uint, ctypes.c_int])
		self.cuCtxSetCurrent = bind("cuCtxSetCurrent", [ctypes.c_void_p])
		self.cuCtxGetCurrent = bind("cuCtxGetCurrent",
			[ctypes.POINTER(ctypes.c_void_p)])
		self.cuCtxSynchronize = bind("cuCtxSynchronize", [])
		self.cuCtxDestroy = bind("cuCtxDestroy", [ctypes.c_void_p])

		# Module management (PTX loading)
		self.cuModuleLoadData = bind("cuModuleLoadData",
			[ctypes.POINTER(ctypes.c_void_p), ctypes.c_void_p])
		self.cuModuleGetFunction = bind("cuModuleGetFunction",
			[ctypes.POINTER(ctypes.c_void_p), ctypes.c_void_p, ctypes.c_char_p])
		self.cuModuleUnload = bind("cuModuleUnload", [ctypes.c_void_p])

		# Memory management
		self.cuMemAlloc = bind("cuMemAlloc",
			[ctypes.POINTER(ctypes.c_ulonglong), ctypes.c_size_t])
		self.cuMemFree = bind("cuMemFree", [ctypes.c_ulonglong])
		self.cuMemcpyHtoD = bind("cuMemcpyHtoD",
			[ctypes.c_ulonglong, ctypes.c_void_p, ctypes.c_size_t])
		self.cuMemcpyDtoH = bind("cuMemcpyDtoH",
			[ctypes.c_void_p, ctypes.c_ulonglong, ctypes.c_size_t])
		self.cuMemsetD8 = bind("cuMemsetD8",
			[ctypes.c_ulonglong, ctypes.c_uint8, ctypes.c_size_t])
		self.cuMemsetD32 = bind("cuMemsetD32",
			[ctypes.c_ulonglong, ctypes.c_uint, ctypes.c_size_t])

		# Async memory copy (for stream-ordered operations)
		self.cuMemcpyHtoDAsync = bind("cuMemcpyHtoDAsync_v2",
			[ctypes.c_ulonglong, ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p])
		self.cuMemcpyDtoHAsync = bind("cuMemcpyDtoHAsync_v2",
			[ctypes.c_void_p, ctypes.c_ulonglong, ctypes.c_size_t, ctypes.c_void_p])

		# Kernel launch
		self.cuLaunchKernel = bind("cuLaunchKernel", [
			ctypes.c_void_p,		# CUfunction f
			ctypes.c_uint,			# gridDimX
			ctypes.c_uint,			# gridDimY
			ctypes.c_uint,			# gridDimZ
			ctypes.c_uint,			# blockDimX
			ctypes.c_uint,			# blockDimY
			ctypes.c_uint,			# blockDimZ
			ctypes.c_uint,			# sharedMemBytes
			ctypes.c_void_p,		# hStream (CUstream)
			ctypes.POINTER(ctypes.c_void_p),  # kernelParams (void**)
			ctypes.c_void_p,		# extra (void**)
		])

		# Stream management
		self.cuStreamCreate = bind("cuStreamCreate",
			[ctypes.POINTER(ctypes.c_void_p), ctypes.c_uint])
		self.cuStreamDestroy = bind("cuStreamDestroy", [ctypes.c_void_p])
		self.cuStreamSynchronize = bind("cuStreamSynchronize", [ctypes.c_void_p])

		# Error handling
		self.cuGetErrorString = bind("cuGetErrorString",
			[ctypes.c_int, ctypes.POINTER(ctypes.c_char_p)])

	def check(self, code: int, context: str = "") -> int:
		"""Check CUDA result code; raise on error."""
		if code != CUDA_SUCCESS:
			err_str = ctypes.c_char_p()
			try:
				self.cuGetErrorString(code, ctypes.byref(err_str))
				msg = err_str.value.decode() if err_str.value else _error_str(code)
			except Exception:
				msg = _error_str(code)
			raise RuntimeError(f"CUDA error ({context}): {msg} (code={code})")
		return code

	def get_error_string(self, code: int) -> str:
		"""Return human-readable CUDA error string."""
		err_str = ctypes.c_char_p()
		try:
			self.cuGetErrorString(code, ctypes.byref(err_str))
			return err_str.value.decode() if err_str.value else _error_str(code)
		except Exception:
			return _error_str(code)


