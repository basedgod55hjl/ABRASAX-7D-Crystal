	def create_stream(self) -> ctypes.c_void_p:
		"""Create a CUDA stream for async operations."""
		drv = self._driver
		stream = ctypes.c_void_p()
		drv.check(drv.cuStreamCreate(ctypes.byref(stream), 0), "cuStreamCreate")
		self._keepalive.append(stream)
		return stream

	def destroy_stream(self, stream: ctypes.c_void_p) -> None:
		"""Destroy a CUDA stream."""
		self._driver.cuStreamDestroy(stream)

	def sync_stream(self, stream: ctypes.c_void_p) -> None:
		"""Synchronize a CUDA stream."""
		self._driver.check(
			self._driver.cuStreamSynchronize(stream), "cuStreamSynchronize"
		)

	def sync(self) -> None:
		"""Synchronize the default CUDA context."""
		self._driver.check(
			self._driver.cuCtxSynchronize(), "cuCtxSynchronize"
		)

