class KernelParams:
	"""Build and hold the void** kernel parameter array for cuLaunchKernel.

	Each kernel argument is converted to a ctypes type and its address is
	stored in the kernelParams array. The storage is kept alive until
	the launch completes.
	"""

	def __init__(self, args: tuple[Any, ...]) -> None:
		self._storage: list[Any] = []
		self._ptrs: list[ctypes.c_void_p] = []
		self._build(args)

	def _build(self, args: tuple[Any, ...]) -> None:
		for arg in args:
			if isinstance(arg, DeviceArray):
				# DeviceArray -> CUdeviceptr (c_uint64)
				cuptr = ctypes.c_uint64(arg.cuptr)
				self._storage.append(cuptr)
			elif isinstance(arg, np.ndarray):
				# numpy array on host -> treat its data address as CUdeviceptr
				# .ctypes.data gives the raw pointer value as int
				cuptr = ctypes.c_uint64(arg.ctypes.data)
				self._storage.append(cuptr)
			elif isinstance(arg, np.int32):
				self._storage.append(ctypes.c_int32(int(arg)))
			elif isinstance(arg, np.float32):
				self._storage.append(ctypes.c_float(float(arg)))
			elif isinstance(arg, np.uint64):
				self._storage.append(ctypes.c_uint64(int(arg)))
			elif isinstance(arg, int):
				self._storage.append(ctypes.c_int32(arg))
			elif isinstance(arg, float):
				self._storage.append(ctypes.c_float(arg))
			elif isinstance(arg, ctypes.c_void_p):
				self._storage.append(arg)
			elif arg is None:
				# NULL pointer
				self._storage.append(ctypes.c_uint64(0))
			else:
				raise TypeError(
					f"Unsupported kernel argument type: {type(arg).__name__} = {arg!r}"
				)
		# Build void** array: each element is a pointer to a stored value
		self._ptrs = [
			ctypes.cast(ctypes.pointer(s), ctypes.c_void_p)
			for s in self._storage
		]

	@property
	def array(self) -> ctypes.Array[ctypes.c_void_p]:
		"""ctypes array of void* pointers (the kernelParams)."""
		return (ctypes.c_void_p * len(self._ptrs))(*self._ptrs)

	def keepalive(self) -> list[Any]:
		"""Return storage list to keep references alive."""
		return self._storage


