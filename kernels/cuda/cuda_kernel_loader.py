class CrystalKernelRuntime:
	"""Primary runtime for 7D mH-Q Crystal CUDA kernels.

	Uses ctypes to bind nvcuda.dll (CUDA Driver API) and loads PTX modules
	from the build/ directory.

	Provides:
	- Low-level: alloc, free, to_device, from_device, launch_kernel
	- High-level: named methods for each kernel (manifold_projection_7d, etc.)

	Usage:
		rt = CrystalKernelRuntime()
		inp = np.random.randn(1024).astype(np.float32)
		out = rt.manifold_projection_7d(inp, dim=64)
	"""

	def __init__(
		self,
		device_id: int = 0,
		ptx_dir: str | Path | None = None,
		use_dll: bool = False,
		log_level: int | None = None,
	) -> None:
		if log_level is not None:
			logger.setLevel(log_level)

		self._driver = CudaDriverAPI()
		self._device_id = device_id
		self._context: ctypes.c_void_p | None = None
		self._modules: dict[str, ctypes.c_void_p] = {}
		self._functions: dict[str, ctypes.c_void_p] = {}
		self._keepalive: list[Any] = []  # prevent GC of ctypes objects

		# Override PTX paths if custom directory given
		if ptx_dir is not None:
			p = Path(ptx_dir).resolve()
			_PTX_FILES["v2"] = p / "crystal_kernels_v2.ptx"
			_PTX_FILES["v1"] = p / "crystal_kernels_v1.ptx"
			_PTX_FILES["physx"] = p / "physx_crystal_dynamics.ptx"

		# Attempt DLL mode first if requested
		if use_dll and _DLL_PATH.exists():
			self._init_from_dll()
		else:
			self._init_cuda_context()
			self._load_ptx_modules()
			self._bind_kernel_functions()

		logger.info(
			"CrystalKernelRuntime initialized (device=%d, kernels=%d)",
			device_id, len(self._functions),
		)

	# ------------------------------------------------------------------
	#  Initialization paths
	# ------------------------------------------------------------------

	def _init_cuda_context(self) -> None:
		"""Initialize CUDA driver and create a context on the target device."""
		drv = self._driver

		# cuInit
		drv.check(drv.cuInit(0), "cuInit")

		# Get device count
		count = ctypes.c_int(0)
		drv.check(drv.cuDeviceGetCount(ctypes.byref(count)), "cuDeviceGetCount")
		if count.value == 0:
			raise RuntimeError("No CUDA-capable devices found.")
		if self._device_id >= count.value:
			raise RuntimeError(
				f"Device {self._device_id} not found (only {count.value} available)."
			)

		# Get device handle
		dev = ctypes.c_int(0)
		drv.check(drv.cuDeviceGet(ctypes.byref(dev), self._device_id), "cuDeviceGet")

		# Get device name
		name_buf = ctypes.create_string_buffer(256)
		drv.check(
			drv.cuDeviceGetName(name_buf, 256, dev),
			"cuDeviceGetName",
		)
		self._device_name = name_buf.value.decode()

		# Get compute capability
		major = ctypes.c_int(0)
		minor = ctypes.c_int(0)
		drv.check(
			drv.cuDeviceGetAttribute(ctypes.byref(major), 75, dev),  # CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MAJOR
			"cuDeviceGetAttribute(CC major)",
		)
		drv.check(
			drv.cuDeviceGetAttribute(ctypes.byref(minor), 76, dev),  # CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MINOR
			"cuDeviceGetAttribute(CC minor)",
		)
		self._compute_capability = (major.value, minor.value)

		# Get total memory
		total_mem = ctypes.c_size_t(0)
		drv.check(
			drv.cuDeviceTotalMem(ctypes.byref(total_mem), dev),
			"cuDeviceTotalMem",
		)
		self._total_memory = total_mem.value

		# Create context
		ctx = ctypes.c_void_p()
		drv.check(
			drv.cuCtxCreate(ctypes.byref(ctx), 0, dev),  # flags=0 for default
			"cuCtxCreate",
		)
		self._context = ctx
		self._keepalive.append(ctx)

		logger.info(
			"GPU: %s  (CC %d.%d, %d MB total)",
			self._device_name,
			self._compute_capability[0],
			self._compute_capability[1],
			self._total_memory // (1024 * 1024),
		)

	def _load_ptx_modules(self) -> None:
		"""Load all PTX files as CUDA modules."""
		drv = self._driver
		missing = [str(p) for p in _PTX_FILES.values() if not p.exists()]
		if missing:
			raise FileNotFoundError(
				"Missing PTX files. Run compile_kernels.bat first.\n"
				+ "\n".join(f"  MISSING: {m}" for m in missing)
			)

		for name, path in _PTX_FILES.items():
			logger.debug("Loading PTX module: %s -> %s", name, path)
			with open(str(path), "rb") as f:
				ptx_data = f.read()

			# cuModuleLoadData takes a null-terminated string (C string)
			# Ensure null termination
			ptx_cstr = ctypes.c_char_p(ptx_data + b"\0")
			mod = ctypes.c_void_p()
			drv.check(
				drv.cuModuleLoadData(ctypes.byref(mod), ptx_cstr),
				f"cuModuleLoadData({name})",
			)
			self._modules[name] = mod
			self._keepalive.append(mod)
			self._keepalive.append(ptx_cstr)
			logger.info("Loaded PTX module: %s (%d bytes)", name, len(ptx_data))

	def _bind_kernel_functions(self) -> None:
		"""Look up every kernel function handle from its PTX module."""
		drv = self._driver
		for alias, kinfo in KERNEL_REGISTRY.items():
			mod = self._modules.get(kinfo.module)
			if mod is None:
				logger.warning("Module %s not loaded for kernel '%s'; skipping.",
							   kinfo.module, alias)
				continue
			try:
				func = ctypes.c_void_p()
				drv.check(
					drv.cuModuleGetFunction(
						ctypes.byref(func), mod, kinfo.func_name.encode(),
					),
					f"cuModuleGetFunction({kinfo.func_name})",
				)
				self._functions[alias] = func
				self._keepalive.append(func)
				logger.debug("Bound kernel: %s -> %s (%s)", alias, kinfo.func_name, kinfo.module)
			except RuntimeError as exc:
				logger.warning("Kernel '%s' (func=%s) not found in module %s: %s",
							   alias, kinfo.func_name, kinfo.module, exc)

	def _init_from_dll(self) -> None:
		"""Initialize using compiled .dll (from compile_o_to_dll.bat)."""
		# This path uses ctypes.CDLL to load the compiled .dll with host wrappers.
		# The .dll contains host-callable extern "C" functions that manage
		# device memory and launch kernels internally.
		raise NotImplementedError(
			"DLL mode not yet implemented. Use default PTX mode instead."
		)

	# ------------------------------------------------------------------
	#  Properties
	# ------------------------------------------------------------------

	@property
	def device_name(self) -> str:
		"""Name of the active GPU device."""
		return getattr(self, "_device_name", "unknown")

	@property
	def compute_capability(self) -> tuple[int, int]:
		"""Compute capability (major, minor) of the active device."""
		return getattr(self, "_compute_capability", (0, 0))

	@property
	def total_memory(self) -> int:
		"""Total device memory in bytes."""
		return getattr(self, "_total_memory", 0)

	@property
	def available_kernels(self) -> list[str]:
		"""List of loaded kernel names."""
		return list(self._functions.keys())

	@property
	def is_initialized(self) -> bool:
		return self._context is not None

	# ------------------------------------------------------------------
	#  Device memory management
	# ------------------------------------------------------------------

	def alloc(self, nbytes: int) -> DeviceArray:
		"""Allocate device memory. Returns DeviceArray handle."""
		drv = self._driver
		cuptr = ctypes.c_ulonglong(0)
		drv.check(drv.cuMemAlloc(ctypes.byref(cuptr), nbytes), "cuMemAlloc")
		finalizer = lambda: self._free_ptr(cuptr.value)  # noqa: E731
		return DeviceArray(cuptr.value, nbytes, finalizer=finalizer)

	def _free_ptr(self, cuptr: int) -> None:
		"""Internal: free a raw CUdeviceptr."""
		try:
			self._driver.cuMemFree(ctypes.c_ulonglong(cuptr))
		except Exception as exc:
			logger.warning("cuMemFree(0x%x) failed: %s", cuptr, exc)

	def free(self, dev: DeviceArray) -> None:
		"""Free device memory."""
		dev.free()

	def to_device(self, dev: DeviceArray, host_arr: np.ndarray) -> None:
		"""Copy host numpy array to device memory (default stream)."""
		assert isinstance(host_arr, np.ndarray), "host_arr must be numpy array"
		nbytes = host_arr.nbytes
		assert nbytes <= dev.size_bytes, (
			f"Host array ({nbytes} bytes) exceeds device allocation ({dev.size_bytes} bytes)"
		)
		drv = self._driver
		drv.check(
			drv.cuMemcpyHtoD(
				ctypes.c_ulonglong(dev.cuptr),
				host_arr.ctypes.data_as(ctypes.c_void_p),
				nbytes,
			),
			"cuMemcpyHtoD",
		)

	def to_device_async(
		self,
		dev: DeviceArray,
		host_arr: np.ndarray,
		stream: ctypes.c_void_p,
	) -> None:
		"""Copy host numpy array to device memory on a specific stream (async)."""
		assert isinstance(host_arr, np.ndarray), "host_arr must be numpy array"
		nbytes = host_arr.nbytes
		assert nbytes <= dev.size_bytes, (
			f"Host array ({nbytes} bytes) exceeds device allocation ({dev.size_bytes} bytes)"
		)
		drv = self._driver
		drv.check(
			drv.cuMemcpyHtoDAsync(
				ctypes.c_ulonglong(dev.cuptr),
				host_arr.ctypes.data_as(ctypes.c_void_p),
				nbytes,
				stream,
			),
			"cuMemcpyHtoDAsync",
		)

	def from_device(
		self,
		dev: DeviceArray,
		shape: tuple[int, ...],
		dtype: type = np.float32,
	) -> np.ndarray:
		"""Copy device memory to host numpy array."""
		host_arr = np.empty(shape, dtype=dtype)
		drv = self._driver
		drv.check(
			drv.cuMemcpyDtoH(
				host_arr.ctypes.data_as(ctypes.c_void_p),
				ctypes.c_ulonglong(dev.cuptr),
				host_arr.nbytes,
			),
			"cuMemcpyDtoH",
		)
		return host_arr

	def memset(self, dev: DeviceArray, value: int = 0) -> None:
		"""Set device memory to a byte value (0-255)."""
		drv = self._driver
		drv.check(
			drv.cuMemsetD8(ctypes.c_ulonglong(dev.cuptr), value & 0xFF, dev.size_bytes),
			"cuMemsetD8",
		)

	def memset32(self, dev: DeviceArray, value: int = 0) -> None:
		"""Set device memory to a 32-bit integer value."""
		drv = self._driver
		n_ints = dev.size_bytes // 4
		drv.check(
			drv.cuMemsetD32(ctypes.c_ulonglong(dev.cuptr), value, n_ints),
			"cuMemsetD32",
		)

