	def _get_grid_block(
		self,
		name: str,
		grid: tuple[int, int, int] | None,
		block: tuple[int, int, int] | None,
		n: int | None = None,
		shape: tuple[int, ...] | None = None,
	) -> tuple[tuple[int, int, int], tuple[int, int, int]]:
		"""Determine grid/block dimensions from kernel info or explicit params."""
		kinfo = KERNEL_REGISTRY.get(name)
		if kinfo is None:
			# Unknown kernel, use defaults
			if grid is None:
				grid = (1, 1, 1)
			if block is None:
				block = (BLOCK_SIZE_1D, 1, 1)
			return grid, block

		if grid is not None and block is not None:
			return grid, block

		if kinfo.dim == 2:
			# 2D kernel. A flat count cannot describe a shape: measured
			# 2026-11-01, an 8x64 field with n=512 gave side=22, so columns
			# 32..63 were never written (max_err 0.83) while 16x16 and 32x32
			# were exact. Prefer the real shape whenever the caller knows it.
			if shape is not None and len(shape) >= 2:
				height, width = int(shape[-2]), int(shape[-1])
			else:
				if n is not None:
					side = int(n ** 0.5)
				else:
					side = 64
				height = width = side
			used_grid = ((width + BLOCK_SIZE_2D_X - 1) // BLOCK_SIZE_2D_X,
						 (height + BLOCK_SIZE_2D_Y - 1) // BLOCK_SIZE_2D_Y, 1)
			used_block = (BLOCK_SIZE_2D_X, BLOCK_SIZE_2D_Y, 1)
		else:
			# 1D kernel
			n_elems = n or 1024
			used_block = (BLOCK_SIZE_1D, 1, 1)
			used_grid = ((n_elems + BLOCK_SIZE_1D - 1) // BLOCK_SIZE_1D, 1, 1)

		if grid is None:
			grid = used_grid
		if block is None:
			block = used_block
		return grid, block

	def launch_kernel(
		self,
		name: str,
		args: tuple[Any, ...],
		grid: tuple[int, int, int] | None = None,
		block: tuple[int, int, int] | None = None,
		shared_mem: int = 0,
		stream: ctypes.c_void_p | None = None,
		first_array_n: int | None = None,
		first_array_shape: tuple[int, ...] | None = None,
	) -> None:
		"""Launch a named kernel with the given arguments.

		Args:
			name: Kernel name (from KERNEL_REGISTRY keys).
			args: Tuple of kernel arguments (DeviceArray, np.ndarray, int, float, etc.).
			grid: (gx, gy, gz) or None for auto-infer.
			block: (bx, by, bz) or None for auto-infer.
			shared_mem: Dynamic shared memory bytes.
			stream: CUDA stream handle or None for default.
			first_array_n: For auto grid inference, use this as N instead of finding
						   the first DeviceArray.
		"""
		func = self._functions.get(name)
		if func is None:
			available = list(self._functions.keys())
			raise KeyError(
				f"Kernel '{name}' not loaded. Available kernels ({len(available)}): "
				f"{', '.join(sorted(available))}"
			)

		# Infer N from first array-like arg if needed for grid computation
		if first_array_n is not None:
			n_elems = first_array_n
		else:
			n_elems = None
			for a in args:
				if isinstance(a, DeviceArray):
					n_elems = a.nfloats
					break
				if isinstance(a, np.ndarray):
					n_elems = a.size
					break

		grid, block = self._get_grid_block(
			name, grid, block, n=n_elems, shape=first_array_shape
		)

		# Build kernel parameter array
		kparams = KernelParams(args)
		params_arr = kparams.array
		self._keepalive.append(kparams)
		self._keepalive.append(params_arr)

		# Launch
		stream_ptr = stream if stream is not None else None
		drv = self._driver
		drv.check(
			drv.cuLaunchKernel(
				func,
				grid[0], grid[1], grid[2],
				block[0], block[1], block[2],
				shared_mem,
				stream_ptr,
				params_arr,
				None,  # extra = NULL
			),
			f"cuLaunchKernel({name})",
		)

